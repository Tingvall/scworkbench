suppressPackageStartupMessages(library(RSQLite))
source <- DBI::dbConnect(SQLite(), tempfile("matrix_stream_copy_source_"))
destination <- DBI::dbConnect(SQLite(), tempfile("matrix_stream_copy_destination_"))
DBI::dbExecute(source, "CREATE TABLE sample(value INTEGER);")
sqliteCopyDatabase(source, destination)
cat("COMMITTED_SOURCE_COPY_OK\n")
DBI::dbBegin(source)
DBI::dbExecute(source, "INSERT INTO sample VALUES(1);")
failure <- tryCatch(sqliteCopyDatabase(source, destination), error = identity)
stopifnot(inherits(failure, "error"), grepl("Failed to copy all data:", conditionMessage(failure), fixed = TRUE))
cat("ACTIVE_WRITE_TRANSACTION_COPY_REJECTED\n", conditionMessage(failure), "\n")
DBI::dbRollback(source)
sqliteCopyDatabase(source, destination)
cat("ROLLED_BACK_SOURCE_RETRY_OK\n")
DBI::dbDisconnect(destination); DBI::dbDisconnect(source)
