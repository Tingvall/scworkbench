args <- commandArgs(TRUE)
.libPaths(c(file.path(args[[1L]],"library"),.libPaths()))
library(scworkbench)
path <- tempfile(fileext=".sqlite");con <- DBI::dbConnect(RSQLite::SQLite(),path)
DBI::dbGetQuery(con,"PRAGMA journal_mode=WAL;")
DBI::dbExecute(con,"CREATE TABLE payload(value TEXT);")
DBI::dbExecute(con,"INSERT INTO payload VALUES('committed-byte-source');")
DBI::dbExecute(con,"CREATE TABLE publication(value INTEGER);")
DBI::dbExecute(con,"PRAGMA cache_size=-8;")
DBI::dbBegin(con)
DBI::dbExecute(con,"INSERT INTO publication VALUES(1);")
DBI::dbExecute(con,"CREATE TABLE spill(value TEXT);")
DBI::dbExecute(con,"INSERT INTO spill WITH RECURSIVE seq(n) AS(VALUES(1) UNION ALL SELECT n+1 FROM seq WHERE n<400) SELECT printf('%01024d',n) FROM seq;")
for(iteration in seq_len(12L)) {
observer <- scworkbench:::.wb_matrix_native_byte_observer(con)
size <- observer$column("1","value","payload")
stopifnot(identical(rawToChar(observer$read(0L,size)),"committed-byte-source"))
observer$finish()
}
DBI::dbCommit(con)
stopifnot(DBI::dbGetQuery(con,"SELECT COUNT(*) n FROM publication;")$n[[1L]]==1L)
DBI::dbBegin(con);DBI::dbExecute(con,"INSERT INTO publication VALUES(2);");DBI::dbRollback(con)
stopifnot(DBI::dbGetQuery(con,"SELECT COUNT(*) n FROM publication;")$n[[1L]]==1L)
DBI::dbDisconnect(con)
reopen <- DBI::dbConnect(RSQLite::SQLite(),path,flags=RSQLite::SQLITE_RO)
stopifnot(DBI::dbGetQuery(reopen,"PRAGMA integrity_check;")[[1L]][[1L]]=="ok")
DBI::dbDisconnect(reopen);unlink(c(path,paste0(path,"-wal"),paste0(path,"-shm")))
cat("NATIVE_BYTE_WRITER_LOCK commit=PASS rollback=PASS reopened_integrity=PASS\n")
