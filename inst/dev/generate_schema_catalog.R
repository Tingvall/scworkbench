# Generate docs/schema_catalog_reference.md from durable schema declarations.

generate_schema_catalog <- function(root = ".", output = file.path(root, "docs", "schema_catalog_reference.md")) {
  root <- normalizePath(root, winslash = "/", mustWork = TRUE)
  if (!"package:scworkbench" %in% search()) devtools::load_all(root, quiet = TRUE)
  files <- sort(list.files(file.path(root, "R"), pattern = "[.]R$", full.names = TRUE))
  pattern <- "CREATE\\s+TABLE\\s+(?:IF\\s+NOT\\s+EXISTS\\s+)?([A-Za-z0-9_]+)"
  rows <- list()
  for (path in files) {
    text <- paste(readLines(path, warn = FALSE), collapse = "\n")
    matches <- regmatches(text, gregexpr(pattern, text, ignore.case = TRUE, perl = TRUE))[[1L]]
    if (!length(matches) || identical(matches[[1L]], "")) next
    tables <- tolower(sub(pattern, "\\1", matches, ignore.case = TRUE, perl = TRUE))
    for (table in tables) rows[[length(rows) + 1L]] <- data.frame(
      table = table,
      declaration_source = sub(paste0("^", root, "/"), "", normalizePath(path, winslash = "/")),
      stringsAsFactors = FALSE
    )
  }
  inventory <- do.call(rbind, rows)
  inventory <- inventory[order(inventory$table), , drop = FALSE]
  stopifnot(!anyDuplicated(inventory$table))
  constrained <- names(scworkbench:::.wb_schema_foreign_key_definitions())
  migrations <- scworkbench:::.wb_bundle_schema_migrations()
  migration_lines <- vapply(migrations, function(x) {
    paste0("- `", x$version, "` — `", x$id, "`")
  }, character(1))
  table_lines <- paste0(
    "| `", inventory$table, "` | `", inventory$declaration_source,
    "` | `R/schema_migrations.R` | ",
    ifelse(inventory$table %in% constrained, "SQLite foreign keys", "table-local keys/checks or application-validated relationship"), " |"
  )
  relationships <- scworkbench:::.wb_schema_identifier_relationships()
  stopifnot(
    nrow(relationships) > 0L,
    all(relationships$table %in% inventory$table),
    all(relationships$classification %in% c(
      "sqlite_foreign_key", "application_validated", "symbolic_or_external"
    )),
    !anyDuplicated(relationships[, c("table", "columns")])
  )
  # Exhaustively discover identifier-shaped durable columns from the actual
  # current schema. Every child occurrence must be classified above; the only
  # exclusions are the explicit row-owned primary identities below.
  scratch <- tempfile("scwb_schema_catalog_")
  scratch_bundle <- wb_init_bundle(scratch, overwrite = TRUE)
  on.exit({
    try(wb_close_bundle(scratch_bundle), silent = TRUE)
    unlink(scratch, recursive = TRUE, force = TRUE)
  }, add = TRUE)
  candidates <- character()
  for (table in sort(DBI::dbListTables(scratch_bundle$con))) {
    fields <- DBI::dbGetQuery(
      scratch_bundle$con, paste0("PRAGMA table_info(", DBI::dbQuoteIdentifier(scratch_bundle$con, table), ");")
    )$name
    identifiers <- fields[grepl("(_id$|_ids_json$|_key$|_set$|_library$)", fields)]
    candidates <- c(candidates, paste(table, identifiers, sep = "."))
  }
  classified <- unlist(Map(function(table, columns) {
    paste(table, trimws(strsplit(columns, ",", fixed = TRUE)[[1L]]), sep = ".")
  }, relationships$table, relationships$columns), use.names = FALSE)
  row_owned <- c(
    "artifacts.artifact_id", "bundle_schema_migrations.migration_id",
    "cell_vectors.vector_id", "cells.cell_id", "datasets.dataset_id",
    "feature_sets.feature_set", "features.feature_id", "matrices.matrix_id",
    "matrix_fragments.fragment_id", "metadata_fields.field_id", "metadata_field_identities.identity_id", "motif_libraries.motif_library",
    "motif_match_sets.motif_match_set", "motifs.motif_key",
    "prov_commits.commit_id", "prov_heads.snapshot_id", "prov_runs.run_id",
    "spaces.space_id", "analysis_capsules.capsule_id",
    "analysis_capsule_outputs.output_id"
  )
  unclassified <- setdiff(candidates, c(classified, row_owned))
  stopifnot(!length(unclassified), all(row_owned %in% candidates))
  wb_close_bundle(scratch_bundle)
  scratch_bundle <- NULL
  unlink(scratch, recursive = TRUE, force = TRUE)
  relationship_lines <- paste0(
    "| `", relationships$table, "` | `", relationships$columns, "` | `",
    relationships$target, "` | `", relationships$classification, "` | ",
    relationships$enforcement, " |"
  )
  lines <- c(
    "<!-- Generated by inst/dev/generate_schema_catalog.R; do not edit directly. -->",
    "# Durable schema catalog",
    "",
    paste0("Current bundle schema version: `", scworkbench:::.wb_bundle_schema_version(), "`."),
    "",
    "`R/schema_migrations.R` is the canonical schema owner. The declaration source column records the compatibility component that declares each table; component helpers are assertion-only once the ledger is current. All creation, ordered upgrade, constraint installation, and lifecycle backfill are orchestrated by the central migration owner.",
    "",
    "## Ordered migrations",
    "",
    migration_lines,
    "",
    "## Backup and rollback policy",
    "",
    "Writable upgrade acquires the exclusive bundle-writer lock before opening its SQLite transaction. An online-verified pre-upgrade backup is retained in the sibling `.BUNDLE.schema-backups/` directory. Every pending migration and ledger record commits in one transaction. Any injected or ordinary failure rolls the transaction back completely and reports the retained backup path. Restore only while the bundle is closed and no writer lock exists. Read-only opening never creates the ledger or runs a migration; it reports `BUNDLE_SCHEMA_UPGRADE_REQUIRED`.",
    "",
    "## Table inventory",
    "",
    "| Table | Declaration source | Canonical migration owner | Referential-integrity mode |",
    "|---|---|---|---|",
    table_lines,
    "",
    "## Identifier relationship classification",
    "",
    paste0("Every identifier-bearing child relationship in the ", nrow(inventory), "-table durable schema is classified below. Generation discovers identifier-shaped columns from a fresh current schema and fails if a column is neither classified nor one of the explicit row-owned primary identities. `sqlite_foreign_key` relationships are compared by exact normalized child columns, parent table/columns, actions, match mode, and canonical deferred declaration. `application_validated` relationships cannot be represented faithfully as ordinary foreign keys because their parent identity is composite, polymorphic, JSON-encoded, or historically snapshot-independent; the named deep-validation boundary is executable. `symbolic_or_external` values are intentionally not required to name a durable registry row."),
    "",
    "| Child table | Child column(s) | Target/meaning | Classification | Enforcement or rationale |",
    "|---|---|---|---|---|",
    relationship_lines
  )
  dir.create(dirname(output), recursive = TRUE, showWarnings = FALSE)
  writeLines(lines, output, useBytes = TRUE)
  invisible(normalizePath(output, winslash = "/", mustWork = TRUE))
}

if (sys.nframe() == 0L) generate_schema_catalog()
