# Generate docs/schema_catalog_reference.md from durable schema declarations.

generate_schema_catalog <- function(root = ".", output = file.path(root, "docs", "schema_catalog_reference.md")) {
  root <- normalizePath(root, winslash = "/", mustWork = TRUE)
  if (!"package:scworkbench" %in% search()) devtools::load_all(root, quiet = TRUE)
  files <- sort(list.files(file.path(root, "R"), pattern = "[.]R$", full.names = TRUE))
  pattern <- "CREATE\\s+TABLE\\s+(?:IF\\s+NOT\\s+EXISTS\\s+)?([A-Za-z0-9_]+)"
  rows <- list()
  for (path in files) {
    text <- paste(readLines(path, warn = FALSE), collapse = "\n")
    matches <- regmatches(text, gregexpr(pattern, text, ignore.case = TRUE, perl = TRUE))[[1L]]
    if (!length(matches) || identical(matches[[1L]], "")) next
    tables <- tolower(sub(pattern, "\\1", matches, ignore.case = TRUE, perl = TRUE))
    for (table in tables) rows[[length(rows) + 1L]] <- data.frame(
      table = table,
      declaration_source = sub(paste0("^", root, "/"), "", normalizePath(path, winslash = "/")),
      stringsAsFactors = FALSE
    )
  }
  inventory <- do.call(rbind, rows)
  inventory <- inventory[order(inventory$table), , drop = FALSE]
  stopifnot(!anyDuplicated(inventory$table))
  constrained <- names(scworkbench:::.wb_schema_foreign_key_definitions())
  migrations <- scworkbench:::.wb_bundle_schema_migrations()
  migration_lines <- vapply(migrations, function(x) {
    paste0("- `", x$version, "` — `", x$id, "`")
  }, character(1))
  table_lines <- paste0(
    "| `", inventory$table, "` | `", inventory$declaration_source,
    "` | `R/schema_migrations.R` | ",
    ifelse(inventory$table %in% constrained, "SQLite foreign keys", "table-local keys/checks or application-validated relationship"), " |"
  )
  lines <- c(
    "<!-- Generated by inst/dev/generate_schema_catalog.R; do not edit directly. -->",
    "# Durable schema catalog",
    "",
    paste0("Current bundle schema version: `", scworkbench:::.wb_bundle_schema_version(), "`."),
    "",
    "`R/schema_migrations.R` is the canonical schema owner. The declaration source column records the compatibility component that declares each table; component helpers are assertion-only once the ledger is current. All creation, ordered upgrade, constraint installation, and lifecycle backfill are orchestrated by the central migration owner.",
    "",
    "## Ordered migrations",
    "",
    migration_lines,
    "",
    "## Backup and rollback policy",
    "",
    "Writable upgrade acquires the exclusive bundle-writer lock before opening its SQLite transaction. An online-verified pre-upgrade backup is retained in the sibling `.BUNDLE.schema-backups/` directory. Every pending migration and ledger record commits in one transaction. Any injected or ordinary failure rolls the transaction back completely and reports the retained backup path. Restore only while the bundle is closed and no writer lock exists. Read-only opening never creates the ledger or runs a migration; it reports `BUNDLE_SCHEMA_UPGRADE_REQUIRED`.",
    "",
    "## Table inventory",
    "",
    "| Table | Declaration source | Canonical migration owner | Referential-integrity mode |",
    "|---|---|---|---|",
    table_lines
  )
  dir.create(dirname(output), recursive = TRUE, showWarnings = FALSE)
  writeLines(lines, output, useBytes = TRUE)
  invisible(normalizePath(output, winslash = "/", mustWork = TRUE))
}

if (sys.nframe() == 0L) generate_schema_catalog()
