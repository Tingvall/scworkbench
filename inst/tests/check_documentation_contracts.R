#!/usr/bin/env Rscript

root <- normalizePath(".", winslash = "/", mustWork = TRUE)
source(file.path(root, "inst/dev/documentation_policy.R"))
policy <- scwb_documentation_policy(root)
manifest <- jsonlite::read_json(file.path(root, "docs/public_documentation_manifest.json"), simplifyVector = TRUE)
stopifnot(identical(sort(manifest$entries$path), sort(vapply(policy$entries, `[[`, character(1), "path"))))
status <- system2("Rscript", c("inst/dev/regenerate_public_docs.R", "--check"))
stopifnot(identical(status, 0L))
tarball <- tempfile("scworkbench_", fileext = ".tar.gz")
old <- setwd(root); on.exit(setwd(old), add = TRUE)
status <- system2("R", c("CMD", "build", ".", "--no-build-vignettes"))
stopifnot(identical(status, 0L))
made <- list.files(root, pattern = "^scworkbench_.*[.]tar[.]gz$", full.names = TRUE)
stopifnot(length(made) >= 1L)
listing <- system2("tar", c("-tzf", made[[length(made)]]), stdout = TRUE)
for (pattern in policy$forbidden_tarball_patterns) stopifnot(!any(grepl(pattern, listing, perl = TRUE)))
required <- c("DESCRIPTION", "LICENSE", "LICENSE.md", "CITATION.cff", "inst/onboarding/README.md", "inst/protocol/pybench-op-v2.schema.json", "inst/documentation_manifest.json")
stopifnot(all(vapply(required, function(x) any(endsWith(listing, paste0("/", x))), logical(1))))
cat("documentation source-package contract: OK\n")
